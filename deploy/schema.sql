CREATE OR REPLACE FUNCTION public.app_bulk_insert(p_token text, p_table text, p_rows jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE uname TEXT; rec JSONB; row_el JSONB; cols TEXT; vals TEXT; res BIGINT := 0; BEGIN SELECT s.username INTO uname FROM app_sessions s WHERE s.token = p_token AND s.expires_at > now(); IF uname IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '未登录或会话已过期'); END IF; IF p_table NOT IN ('trades','watchlist','quotes','settings','op_logs') THEN RETURN jsonb_build_object('ok', false, 'msg', '非法表名'); END IF; IF jsonb_typeof(p_rows) <> 'array' THEN RETURN jsonb_build_object('ok', false, 'msg', '数据格式错误'); END IF; FOR row_el IN SELECT * FROM jsonb_array_elements(p_rows) LOOP rec := (row_el - 'id' - 'owner_id' - 'created_at') || jsonb_build_object('owner_id', uname); SELECT string_agg(quote_ident(c.column_name), ', '), string_agg('(v.r).' || quote_ident(c.column_name), ', ') INTO cols, vals FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = p_table AND c.column_name <> 'id' AND jsonb_exists(rec, c.column_name); IF cols IS NULL THEN CONTINUE; END IF; BEGIN EXECUTE format('INSERT INTO %I (%s) SELECT %s FROM (SELECT jsonb_populate_record(NULL::%I, $1) AS r) v', p_table, cols, vals, p_table) USING rec; res := res + 1; EXCEPTION WHEN unique_violation THEN NULL; WHEN check_violation THEN NULL; WHEN not_null_violation THEN NULL; END; END LOOP; RETURN jsonb_build_object('ok', true, 'count', res); END $function$;

