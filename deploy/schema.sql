CREATE OR REPLACE FUNCTION public.app_query(p_token text, p_table text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE uname TEXT; res JSONB; BEGIN SELECT s.username INTO uname FROM app_sessions s WHERE s.token = p_token AND s.expires_at > now(); IF uname IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '未登录或会话已过期'); END IF; IF p_table NOT IN ('trades','watchlist','quotes','settings','op_logs','qa_history') THEN RETURN jsonb_build_object('ok', false, 'msg', '非法表名'); END IF; EXECUTE format('SELECT COALESCE(jsonb_agg(x), ''[]''::jsonb) FROM (SELECT to_jsonb(t) AS x FROM %I t WHERE t.owner_id = $1 ORDER BY t.id DESC) s', p_table) INTO res USING uname; RETURN jsonb_build_object('ok', true, 'data', res); END $function$;

CREATE OR REPLACE FUNCTION public.app_insert(p_token text, p_table text, p_data jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE uname TEXT; rec JSONB; res JSONB; cols TEXT; vals TEXT; BEGIN SELECT s.username INTO uname FROM app_sessions s WHERE s.token = p_token AND s.expires_at > now(); IF uname IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '未登录或会话已过期'); END IF; IF p_table NOT IN ('trades','watchlist','quotes','settings','op_logs','qa_history') THEN RETURN jsonb_build_object('ok', false, 'msg', '非法表名'); END IF; IF jsonb_typeof(p_data) <> 'object' THEN RETURN jsonb_build_object('ok', false, 'msg', '数据格式错误'); END IF; rec := (p_data - 'id' - 'owner_id' - 'created_at') || jsonb_build_object('owner_id', uname); SELECT string_agg(quote_ident(c.column_name), ', '), string_agg('(v.r).' || quote_ident(c.column_name), ', ') INTO cols, vals FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = p_table AND c.column_name <> 'id' AND jsonb_exists(rec, c.column_name); IF cols IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '无有效字段'); END IF; BEGIN EXECUTE format('INSERT INTO %I (%s) SELECT %s FROM (SELECT jsonb_populate_record(NULL::%I, $1) AS r) v RETURNING to_jsonb(%I.*)', p_table, cols, vals, p_table, p_table) INTO res USING rec; EXCEPTION WHEN unique_violation THEN RETURN jsonb_build_object('ok', false, 'msg', '记录已存在（重复添加）'); WHEN check_violation THEN RETURN jsonb_build_object('ok', false, 'msg', '数据校验失败，请检查字段'); WHEN not_null_violation THEN RETURN jsonb_build_object('ok', false, 'msg', '必填字段缺失'); END; RETURN jsonb_build_object('ok', true, 'data', res); END $function$;

CREATE OR REPLACE FUNCTION public.app_update(p_token text, p_table text, p_id bigint, p_data jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE uname TEXT; rec JSONB; cols_all TEXT; cols_rest TEXT; res JSONB; v_cnt BIGINT; BEGIN SELECT s.username INTO uname FROM app_sessions s WHERE s.token = p_token AND s.expires_at > now(); IF uname IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '未登录或会话已过期'); END IF; IF p_table NOT IN ('trades','watchlist','quotes','settings','op_logs') THEN RETURN jsonb_build_object('ok', false, 'msg', '非法表名'); END IF; IF jsonb_typeof(p_data) <> 'object' THEN RETURN jsonb_build_object('ok', false, 'msg', '数据格式错误'); END IF; EXECUTE format('SELECT to_jsonb(t.*) FROM %I t WHERE t.id = $1 AND t.owner_id = $2', p_table) INTO rec USING p_id, uname; IF rec IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '记录不存在或无权修改'); END IF; rec := ((rec || (p_data - 'owner_id' - 'id')) - 'id') || jsonb_build_object('owner_id', uname); SELECT string_agg(quote_ident(column_name), ', ' ORDER BY ordinal_position), string_agg('(v.r).' || quote_ident(column_name), ', ' ORDER BY ordinal_position) INTO cols_all, cols_rest FROM information_schema.columns WHERE table_schema = 'public' AND table_name = p_table AND column_name NOT IN ('id', 'owner_id'); EXECUTE format('UPDATE %I t SET (owner_id, %s) = ((v.r).owner_id, %s) FROM (SELECT jsonb_populate_record(NULL::%I, $1) AS r) v WHERE t.id = $2 AND t.owner_id = $3 RETURNING to_jsonb(t.*)', p_table, cols_all, cols_rest, p_table) INTO res USING rec, p_id, uname; GET DIAGNOSTICS v_cnt = ROW_COUNT; IF v_cnt = 0 THEN RETURN jsonb_build_object('ok', false, 'msg', '更新失败'); END IF; RETURN jsonb_build_object('ok', true, 'data', res); END $function$;

