-- ============================================================================
-- 操作日记 · 自托管数据库 schema（v3.10.2，从 WorkBuddy 云库逐字导出重建）
-- ============================================================================
-- 特性：
--   · 幂等 —— 可重复执行（升级时直接重跑本文件即可，不动数据）
--   · 与云端同构 —— 9 表 + 18 个 RPC 函数 + RLS 策略，前端零改动
-- 执行方式：psql -d stockjournal -f schema.sql（需要数据库属主或超级用户权限）
-- ============================================================================

-- ① 依赖扩展（crypt / gen_salt / gen_random_bytes）
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ② auth.uid() 兼容 shim（云端平台的 auth 扩展在自建库不存在；
--    业务表 owner_id 的 DEFAULT 引用它。全部数据写入都走下面的
--    SECURITY DEFINER 函数、显式指定 owner_id，该函数本身永远返回 NULL）
CREATE SCHEMA IF NOT EXISTS auth;
CREATE OR REPLACE FUNCTION auth.uid() RETURNS text LANGUAGE sql STABLE
AS $$ SELECT NULL::text $$;

-- ============================================================================
-- ③ 表（9 张）
-- ============================================================================

CREATE TABLE IF NOT EXISTS trades (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  transaction_time timestamptz NOT NULL,
  transaction_type text NOT NULL,
  stock_code varchar(10) NOT NULL,
  stock_name varchar(50),
  market varchar(2) NOT NULL DEFAULT 'sh',
  quantity integer NOT NULL,
  price numeric NOT NULL,
  gross_amount numeric,
  fee jsonb NOT NULL DEFAULT '{}'::jsonb,
  net_amount numeric,
  note varchar(500),
  source varchar(10) NOT NULL DEFAULT 'manual',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS watchlist (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  stock_code varchar(10) NOT NULL,
  stock_name varchar(50),
  group_name varchar(30) DEFAULT '默认',
  note varchar(500),
  cur_price numeric,
  prev_close numeric,
  starred boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS quotes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  stock_code varchar(10) NOT NULL,
  stock_name varchar(50),
  price numeric,
  prev_close numeric,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS settings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  key text NOT NULL,
  value jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS op_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  action varchar(20) NOT NULL,
  summary varchar(300),
  ref_table varchar(20),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS qa_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL DEFAULT auth.uid(),
  conversation_id text NOT NULL,
  question text NOT NULL DEFAULT '',
  answer text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'user',
  must_change_pwd boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_sessions (
  token text NOT NULL PRIMARY KEY,
  username text NOT NULL,
  expires_at timestamptz NOT NULL DEFAULT (now() + '30 days'::interval),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 全市场日K库（每股一行，bars 为紧凑数组 JSON；动量筛选数据底座）
CREATE TABLE IF NOT EXISTS kline_cache (
  code text PRIMARY KEY,
  name text,
  bars jsonb NOT NULL DEFAULT '[]'::jsonb,
  days integer NOT NULL DEFAULT 0,
  updated date,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ============================================================================
-- ④ RLS + 授权（6 张业务表；app_users / app_sessions / kline_cache 不开 RLS，
--    只经 SECURITY DEFINER 函数访问 —— 与云端一致）
-- ============================================================================

DO $$ DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['trades','watchlist','quotes','settings','op_logs','qa_history'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON %I', t || '_owner_all', t);
    EXECUTE format($p$CREATE POLICY %I ON %I FOR ALL
      USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid())$p$, t || '_owner_all', t);
  END LOOP;
END $$;

-- ============================================================================
-- ⑤ RPC 函数（18 个，SECURITY DEFINER，鉴权 = p_token 查 app_sessions，30 天过期）
-- ============================================================================

CREATE OR REPLACE FUNCTION public.app_has_users()
 RETURNS boolean
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ SELECT EXISTS (SELECT 1 FROM app_users) $function$;

CREATE OR REPLACE FUNCTION public.app_setup_admin(p_username text, p_password text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE v_cnt BIGINT; BEGIN IF char_length(p_username) < 2 OR char_length(p_username) > 30 THEN RETURN jsonb_build_object('ok', false, 'msg', '用户名长度需 2-30 个字符'); END IF; IF char_length(p_password) < 6 THEN RETURN jsonb_build_object('ok', false, 'msg', '密码至少 6 位'); END IF; SELECT COUNT(*) INTO v_cnt FROM app_users; IF v_cnt > 0 THEN RETURN jsonb_build_object('ok', false, 'msg', '系统已初始化，请联系管理员创建账号'); END IF; INSERT INTO app_users (username, password_hash, role) VALUES (p_username, crypt(p_password, gen_salt('bf')), 'admin'); RETURN jsonb_build_object('ok', true); END $function$;

CREATE OR REPLACE FUNCTION public.app_login(p_username text, p_password text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE u app_users%ROWTYPE; v_token TEXT; BEGIN DELETE FROM app_sessions WHERE expires_at < now(); SELECT * INTO u FROM app_users WHERE username = p_username; IF NOT FOUND OR u.password_hash <> crypt(p_password, u.password_hash) THEN RETURN jsonb_build_object('ok', false, 'msg', '用户名或密码错误'); END IF; v_token := replace(encode(gen_random_bytes(18), 'hex'), '/', 'x'); INSERT INTO app_sessions (token, username) VALUES (v_token, u.username); RETURN jsonb_build_object('ok', true, 'token', v_token, 'username', u.username, 'role', u.role, 'must_change_pwd', u.must_change_pwd); END $function$;

