 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ BEGIN DELETE FROM app_sessions WHERE token = p_token; RETURN jsonb_build_object('ok', true); END $function$;

CREATE OR REPLACE FUNCTION public.app_change_pwd(p_token text, p_old text, p_new text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE uname TEXT; h TEXT; BEGIN IF char_length(p_new) < 6 THEN RETURN jsonb_build_object('ok', false, 'msg', '新密码至少 6 位'); END IF; SELECT s.username, u.password_hash INTO uname, h FROM app_sessions s JOIN app_users u ON u.username = s.username WHERE s.token = p_token AND s.expires_at > now(); IF uname IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '未登录或会话已过期'); END IF; IF h <> crypt(p_old, h) THEN RETURN jsonb_build_object('ok', false, 'msg', '当前密码不正确'); END IF; UPDATE app_users SET password_hash = crypt(p_new, gen_salt('bf')), must_change_pwd = false WHERE username = uname; RETURN jsonb_build_object('ok', true); END $function$;

CREATE OR REPLACE FUNCTION public.app_create_user(p_token text, p_username text, p_password text, p_role text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE caller_role TEXT; BEGIN SELECT u.role INTO caller_role FROM app_sessions s JOIN app_users u ON u.username = s.username WHERE s.token = p_token AND s.expires_at > now(); IF caller_role IS DISTINCT FROM 'admin' THEN RETURN jsonb_build_object('ok', false, 'msg', '仅管理员可创建账号'); END IF; IF p_role NOT IN ('admin','user') THEN p_role := 'user'; END IF; IF char_length(p_username) < 2 OR char_length(p_username) > 30 THEN RETURN jsonb_build_object('ok', false, 'msg', '用户名长度需 2-30 个字符'); END IF; IF char_length(p_password) < 6 THEN RETURN jsonb_build_object('ok', false, 'msg', '密码至少 6 位'); END IF; BEGIN INSERT INTO app_users (username, password_hash, role, must_change_pwd) VALUES (p_username, crypt(p_password, gen_salt('bf')), p_role, true); EXCEPTION WHEN unique_violation THEN RETURN jsonb_build_object('ok', false, 'msg', '用户名已存在'); END; RETURN jsonb_build_object('ok', true); END $function$;

CREATE OR REPLACE FUNCTION public.app_delete_user(p_token text, p_username text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE caller_role TEXT; v_admin_cnt BIGINT; BEGIN SELECT u.role INTO caller_role FROM app_sessions s JOIN app_users u ON u.username = s.username WHERE s.token = p_token AND s.expires_at > now(); IF caller_role IS DISTINCT FROM 'admin' THEN RETURN jsonb_build_object('ok', false, 'msg', '仅管理员可删除账号'); END IF; IF p_username = (SELECT username FROM app_sessions WHERE token = p_token) THEN RETURN jsonb_build_object('ok', false, 'msg', '不能删除当前登录账号'); END IF; SELECT COUNT(*) INTO v_admin_cnt FROM app_users WHERE role = 'admin'; IF v_admin_cnt <= 1 AND EXISTS (SELECT 1 FROM app_users WHERE username = p_username AND role = 'admin') THEN RETURN jsonb_build_object('ok', false, 'msg', '至少保留一个管理员'); END IF; DELETE FROM trades WHERE owner_id = p_username; DELETE FROM watchlist WHERE owner_id = p_username; DELETE FROM quotes WHERE owner_id = p_username; DELETE FROM settings WHERE owner_id = p_username; DELETE FROM op_logs WHERE owner_id = p_username; DELETE FROM app_users WHERE username = p_username; IF NOT FOUND THEN RETURN jsonb_build_object('ok', false, 'msg', '用户不存在'); END IF; RETURN jsonb_build_object('ok', true); END $function$;

