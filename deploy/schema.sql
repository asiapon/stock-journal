CREATE OR REPLACE FUNCTION public.kline_all(p_token text, p_since date DEFAULT NULL::date)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE uname TEXT; res JSONB; BEGIN SELECT s.username INTO uname FROM app_sessions s WHERE s.token = p_token AND s.expires_at > now(); IF uname IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '未登录或会话已过期'); END IF; IF p_since IS NULL THEN EXECUTE 'SELECT COALESCE(jsonb_agg(jsonb_build_object(''code'', t.code, ''name'', t.name, ''bars'', t.bars, ''days'', t.days, ''updated'', t.updated)), ''[]''::jsonb) FROM kline_cache t' INTO res; ELSE EXECUTE 'SELECT COALESCE(jsonb_agg(jsonb_build_object(''code'', t.code, ''name'', t.name, ''bars'', t.bars, ''days'', t.days, ''updated'', t.updated)), ''[]''::jsonb) FROM kline_cache t WHERE t.updated >= $1' INTO res USING p_since; END IF; RETURN jsonb_build_object('ok', true, 'data', res); END $function$;

CREATE OR REPLACE FUNCTION public.kline_upsert(p_token text, p_rows jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ DECLARE uname TEXT; row_el JSONB; res BIGINT := 0; BEGIN SELECT s.username INTO uname FROM app_sessions s WHERE s.token = p_token AND s.expires_at > now(); IF uname IS NULL THEN RETURN jsonb_build_object('ok', false, 'msg', '未登录或会话已过期'); END IF; IF jsonb_typeof(p_rows) <> 'array' THEN RETURN jsonb_build_object('ok', false, 'msg', '数据格式错误'); END IF; FOR row_el IN SELECT * FROM jsonb_array_elements(p_rows) LOOP BEGIN INSERT INTO kline_cache (code, name, bars, days, updated) VALUES (row_el->>'code', row_el->>'name', COALESCE(row_el->'bars', '[]'::jsonb), COALESCE((row_el->>'days')::int, jsonb_array_length(COALESCE(row_el->'bars', '[]'::jsonb))), (row_el->>'updated')::date) ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, bars = EXCLUDED.bars, days = EXCLUDED.days, updated = EXCLUDED.updated, updated_at = now(); res := res + 1; EXCEPTION WHEN OTHERS THEN NULL; END; END LOOP; RETURN jsonb_build_object('ok', true, 'count', res); END $function$;

